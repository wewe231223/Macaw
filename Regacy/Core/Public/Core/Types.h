/**
 * @file Types.h
 * @brief 고정 비트 폭의 부호 있는 정수와 부호 없는 정수 별칭을 제공합니다.
 */
#pragma once

#include <cstdint>
#include <memory>

/**
 * @brief 8비트 부호 있는 정수 타입입니다.
 */
using int8 = int8_t;
/**
 * @brief 16비트 부호 있는 정수 타입입니다.
 */
using int16 = int16_t;
/**
 * @brief 32비트 부호 있는 정수 타입입니다.
 */
using int32 = int32_t;
/**
 * @brief 64비트 부호 있는 정수 타입입니다.
 */
using int64 = int64_t;

/**
 * @brief 8비트 부호 없는 정수 타입입니다.
 */
using uint8 = uint8_t;
/**
 * @brief 16비트 부호 없는 정수 타입입니다.
 */
using uint16 = uint16_t;
/**
 * @brief 32비트 부호 없는 정수 타입입니다.
 */
using uint32 = uint32_t;
/**
 * @brief 64비트 부호 없는 정수 타입입니다.
 */
using uint64 = uint64_t;
